        public static bool Has(string name) => name != null && Data.ContainsKey(name);

        public static Texture2D Get(string name)
        {
            if (name == null || !Data.ContainsKey(name)) name = "box";
            if (cache.TryGetValue(name, out var t) && t != null) return t;
            var rows = Data[name];
            t = new Texture2D(Size, Size, TextureFormat.RGBA32, false) { filterMode = FilterMode.Point, wrapMode = TextureWrapMode.Clamp, name = "Icon_" + name };
            var px = new Color32[Size * Size];
            for (int r = 0; r < Size && r < rows.Length; r++)
                for (int c = 0; c < Size && c < rows[r].Length; c++)
                {
                    char ch = rows[r][c];
                    byte a = ch == '#' ? (byte)255 : ch == '+' ? (byte)110 : (byte)0;
                    px[(Size - 1 - r) * Size + c] = new Color32(255, 255, 255, a);
                }
            t.SetPixels32(px);
            t.Apply(false, false);
            cache[name] = t;
            return t;
        }

        public static void Draw(Rect r, string name, Color col)
        {
            if (Event.current.type != EventType.Repaint) return;
            var old = GUI.color;
            GUI.color = col;
            GUI.DrawTexture(r, Get(name));
            GUI.color = old;
        }
